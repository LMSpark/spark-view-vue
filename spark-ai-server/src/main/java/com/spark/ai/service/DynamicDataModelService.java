    private Map<String, Object> persistImportedOrCreatedTable(
            String tenantId,
            String projectId,
            String logicalName,
            String physicalName,
            String origin,
            Map<String, Object> requestBody,
            IntrospectedTable introspected
    ) {
        String primaryKey = introspected.primaryKeyColumns().stream()
                .findFirst()
                .map(DynamicDataModelService::toLowerCamel)
                .orElse("id");
        Timestamp now = Timestamp.from(Instant.now());
        String ddlHash = hashTable(introspected);
        Long databaseId = readNullableLong(requestBody.get("databaseId"));
        jdbcTemplate.update("""
            INSERT INTO DATA_MODEL_TABLE (
                TENANT_ID, PROJECT_ID, LOGICAL_TABLE_NAME, ORIGIN, MANAGED_MODE,
                PHYSICAL_TABLE_NAME, PRIMARY_KEY_FIELD, RESOURCE_TYPE, RESOURCE_ID,
                BUSINESS_CATEGORY, DATABASE_ID, ISOLATION_MODE, SCHEMA_VERSION, DDL_HASH, STATUS,
                LAST_INTROSPECTED_AT, CREATED_AT, UPDATED_AT
            ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, 'active', ?, ?, ?)
            """,
                tenantId,
                projectId,
                logicalName,
                origin,
                MANAGED_MODE_STRICT,
                introspected.tableName(),
                primaryKey,
                stringOrDefault(requestBody.get("resourceType"), "database-table"),
                stringOrDefault(requestBody.get("resourceId"), logicalName),
                stringOrDefault(requestBody.get("businessCategory"), null),
                databaseId,
                DataIsolationMode.parseOrDefault(requestBody.get("isolationMode"), DataIsolationMode.PROJECT_ISOLATED, "isolationMode").name(),
                1,
                ddlHash,
                now,
                now,
                now
        );
        TableInfo table = Objects.requireNonNull(findTable(tenantId, projectId, logicalName));
        replaceColumnsFromIntrospection(table.id(), introspected);
        return getTablePayload(tenantId, projectId, logicalName);
    }

    private void createPhysicalTable(JdbcTemplate targetJdbc, DatabaseDialect targetDialect, String physicalName, List<ColumnDraft> columns) {
        List<String> definitions = new ArrayList<>();
        definitions.add(targetDialect.quoteIdentifier("TENANT_ID") + " VARCHAR(255) NOT NULL");
        definitions.add(targetDialect.quoteIdentifier("PROJECT_ID") + " VARCHAR(255) NOT NULL");
        for (ColumnDraft column : columns) {
            definitions.add(targetDialect.columnDefinition(toDialectColumn(column), true));
        }
        targetJdbc.execute("CREATE TABLE " + targetDialect.quoteIdentifier(physicalName) + " (" + String.join(", ", definitions) + ")" + targetDialect.createTableSuffix());
        createIndexIfMissing(targetJdbc, targetDialect, physicalName, "IDX_" + physicalName + "_SCOPE", List.of("TENANT_ID", "PROJECT_ID"));
    }

    private void ensureManagedPhysicalShape(String tenantId, String projectId, IntrospectedTable table) {
        boolean hasPrimaryKey = !table.primaryKeyColumns().isEmpty();
        if (!hasColumn(table, "TENANT_ID")) {
            jdbcTemplate.execute(dialect.addRawColumnSql(table.tableName(), "TENANT_ID", "VARCHAR(255)"));
            jdbcTemplate.update("UPDATE " + q(table.tableName()) + " SET " + q("TENANT_ID") + " = ? WHERE " + q("TENANT_ID") + " IS NULL", tenantId);
            tryAlter(dialect.setNotNullSql(table.tableName(), "TENANT_ID", "VARCHAR(255)"));
        }
        if (!hasColumn(table, "PROJECT_ID")) {
            jdbcTemplate.execute(dialect.addRawColumnSql(table.tableName(), "PROJECT_ID", "VARCHAR(255)"));
            jdbcTemplate.update("UPDATE " + q(table.tableName()) + " SET " + q("PROJECT_ID") + " = ? WHERE " + q("PROJECT_ID") + " IS NULL", projectId);
            tryAlter(dialect.setNotNullSql(table.tableName(), "PROJECT_ID", "VARCHAR(255)"));
        }
        if (!hasPrimaryKey) {
            jdbcTemplate.execute(dialect.addIdentityPrimaryKeyColumnSql(table.tableName(), "ID"));
            if (dialect != DatabaseDialect.MYSQL) {
                tryAlter("ALTER TABLE " + q(table.tableName()) + " ADD PRIMARY KEY (" + q("ID") + ")");
            }
        }
        createIndexIfMissing(table.tableName(), "IDX_" + table.tableName() + "_SCOPE", List.of("TENANT_ID", "PROJECT_ID"));
    }

    private void createIndexIfMissing(JdbcTemplate targetJdbc, DatabaseDialect targetDialect, String tableName, String indexName, List<String> columnNames) {
        if (indexExists(targetJdbc, tableName, indexName)) {
            return;
        }
        targetJdbc.execute(targetDialect.createIndexSql(tableName, indexName, columnNames));
    }

    private void createIndexIfMissing(String tableName, String indexName, List<String> columnNames) {
        createIndexIfMissing(jdbcTemplate, dialect, tableName, indexName, columnNames);
    }

    private boolean indexExists(JdbcTemplate targetJdbc, String tableName, String indexName) {
        DataSource targetDataSource = targetJdbc.getDataSource();
        if (targetDataSource == null) {
            targetDataSource = dataSource;
        }
        try (Connection connection = targetDataSource.getConnection()) {
            DatabaseMetaData metaData = connection.getMetaData();
            String actualTableName = resolveActualTableName(metaData, tableName);
            if (actualTableName == null) return false;
            try (ResultSet rs = metaData.getIndexInfo(null, null, actualTableName, false, false)) {
                while (rs.next()) {
                    String actualIndex = rs.getString("INDEX_NAME");
                    if (actualIndex != null && actualIndex.equalsIgnoreCase(indexName)) {
                        return true;
                    }
                }
            }
            return false;
        } catch (SQLException e) {
            throw new IllegalStateException("扫描数据库索引失败: " + tableName + "." + indexName, e);
        }
    }

    private void tryAlter(String sql) {
        try {
            jdbcTemplate.execute(sql);
        } catch (Exception ignored) {
            // 部分历史表约束变更会被数据库拒绝；接管流程随后用 consistency 暴露差异。
        }
    }

    private IntrospectedTable scanPhysicalTable(JdbcTemplate targetJdbc, String physicalTableName) {
        assertIdentifier(physicalTableName, "physicalTableName");
        DataSource ds = targetJdbc.getDataSource();
        if (ds == null) ds = dataSource;
        try (Connection connection = ds.getConnection()) {
            DatabaseMetaData metaData = connection.getMetaData();
            String tableName = resolveActualTableName(metaData, physicalTableName);
            if (tableName == null) {
                throw new NoSuchElementException("物理表不存在: " + physicalTableName);
            }

            Set<String> primaryKeys = new LinkedHashSet<>();
            try (ResultSet pk = metaData.getPrimaryKeys(null, null, tableName)) {
                while (pk.next()) {
                    primaryKeys.add(pk.getString("COLUMN_NAME"));
                }
            }

            List<IntrospectedColumn> columns = new ArrayList<>();
            try (ResultSet rs = metaData.getColumns(null, null, tableName, null)) {
                while (rs.next()) {
                    String columnName = rs.getString("COLUMN_NAME");
                    int sqlTypeCode = rs.getInt("DATA_TYPE");
                    String typeName = rs.getString("TYPE_NAME");
                    int size = rs.getInt("COLUMN_SIZE");
                    int scale = rs.getInt("DECIMAL_DIGITS");
                    boolean nullable = rs.getInt("NULLABLE") != DatabaseMetaData.columnNoNulls;
                    String defaultValue = rs.getString("COLUMN_DEF");
                    int ordinalPosition = rs.getInt("ORDINAL_POSITION");
                    String autoIncrement = "";
                    try {
                        autoIncrement = rs.getString("IS_AUTOINCREMENT");
                    } catch (Exception ignored) {
                        // Driver optional column.
                    }
                    columns.add(new IntrospectedColumn(
                            columnName,
                            sqlTypeCode,
                            typeName,
                            size > 0 ? size : null,
                            scale >= 0 ? scale : null,
                            nullable,
                            defaultValue,
                            primaryKeys.contains(columnName),
                            "YES".equalsIgnoreCase(autoIncrement),
                            ordinalPosition
                    ));
                }
            }
            columns.sort(Comparator.comparingInt(IntrospectedColumn::ordinalPosition));
            return new IntrospectedTable(tableName, columns, primaryKeys);
        } catch (SQLException e) {
            throw new IllegalStateException("扫描数据库表失败: " + physicalTableName, e);
        }
    }

    private IntrospectedTable scanPhysicalTable(String physicalTableName) {
        return scanPhysicalTable(jdbcTemplate, physicalTableName);
    }

    private String resolveActualTableName(DatabaseMetaData metaData, String requestedName) throws SQLException {
        try (ResultSet rs = metaData.getTables(null, null, requestedName, new String[]{"TABLE"})) {
            if (rs.next()) return rs.getString("TABLE_NAME");
        }
        try (ResultSet rs = metaData.getTables(null, null, requestedName.toUpperCase(Locale.ROOT), new String[]{"TABLE"})) {
            if (rs.next()) return rs.getString("TABLE_NAME");
        }
        return null;
    }

    private List<String> listPhysicalTableNames() {
        try (Connection connection = dataSource.getConnection()) {
            DatabaseMetaData metaData = connection.getMetaData();
            List<String> names = new ArrayList<>();
            try (ResultSet rs = metaData.getTables(null, null, null, new String[]{"TABLE"})) {
                while (rs.next()) {
                    String schema = rs.getString("TABLE_SCHEM");
                    String name = rs.getString("TABLE_NAME");
                    if (isImportableTable(schema, name)) {
                        names.add(name);
                    }
                }
            }
            names.sort(String::compareToIgnoreCase);
            return names;
        } catch (SQLException e) {
            throw new IllegalStateException("扫描数据库表失败", e);
        }
    }

    private boolean isImportableTable(String schema, String tableName) {
        if (tableName == null) return false;
        String upperSchema = schema == null ? "" : schema.toUpperCase(Locale.ROOT);
        String upper = tableName.toUpperCase(Locale.ROOT);
        if (upperSchema.contains("INFORMATION_SCHEMA")) return false;
        if (upper.startsWith("SYS")) return false;
        return !RESERVED_TABLES.contains(upper);
    }

    private Map<String, Object> describePhysicalTable(String physicalTableName, boolean includeColumns) {
        IntrospectedTable table = scanPhysicalTable(physicalTableName);
        Map<String, Object> payload = new LinkedHashMap<>();
        payload.put("physicalTableName", table.tableName());
        payload.put("primaryKeyColumns", table.primaryKeyColumns());
        payload.put("managed", isManagedPhysicalTable(table.tableName()));
        if (includeColumns) {
            payload.put("columns", table.columns().stream().map(this::toIntrospectionPayload).toList());
        }
        return payload;
    }

    private boolean isManagedPhysicalTable(String physicalTableName) {
        Integer count = jdbcTemplate.queryForObject(
                "SELECT COUNT(*) FROM DATA_MODEL_TABLE WHERE PHYSICAL_TABLE_NAME = ?",
                Integer.class,
                physicalTableName
        );
        return count != null && count > 0;
    }

    private void replaceColumnsFromIntrospection(long tableId, IntrospectedTable table) {
        jdbcTemplate.update("DELETE FROM DATA_MODEL_COLUMN WHERE TABLE_ID = ?", tableId);
        Timestamp now = Timestamp.from(Instant.now());
        int ordinal = 0;
        for (IntrospectedColumn physical : table.columns()) {
            if (SYSTEM_PHYSICAL_COLUMNS.contains(physical.columnName().toUpperCase(Locale.ROOT))) {
                continue;
            }
            String logical = toLowerCamel(physical.columnName());
            jdbcTemplate.update("""
                INSERT INTO DATA_MODEL_COLUMN (
                    TABLE_ID, COLUMN_NAME, PHYSICAL_COLUMN_NAME, DATA_TYPE, SQL_TYPE,
                    ORDINAL_POSITION, IS_PRIMARY_KEY, IS_AUTO_INCREMENT, IS_NULLABLE,
                    IS_REQUIRED, MAX_LENGTH, NUMERIC_PRECISION, NUMERIC_SCALE,
                    DEFAULT_VALUE, LABEL, CREATED_AT, UPDATED_AT
                ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
                """,
                    tableId,
                    logical,
                    physical.columnName(),
                    dataTypeFromSqlType(physical),
                    sqlTypeFromIntrospection(physical),
                    ordinal++,
                    physical.primaryKey(),
                    physical.autoIncrement(),
                    physical.nullable(),
                    !physical.nullable(),
                    physical.size(),
                    physical.size(),
                    physical.scale(),
                    physical.defaultValue(),
                    humanizeLabel(logical),
                    now,
                    now
            );
        }
    }

    private void updateTableHashAndVersion(long tableId, String ddlHash, int schemaVersion) {
        Timestamp now = Timestamp.from(Instant.now());
        jdbcTemplate.update("""
            UPDATE DATA_MODEL_TABLE
            SET DDL_HASH = ?, SCHEMA_VERSION = ?, LAST_INTROSPECTED_AT = ?, UPDATED_AT = ?
            WHERE ID = ?
            """, ddlHash, schemaVersion, now, now, tableId);
    }

    private TableInfo findTable(String tenantId, String projectId, String logicalTableName) {
        ScopePredicate scope = tableScopePredicate(tenantId, projectId, "LOGICAL_TABLE_NAME = ?");
        List<Object> args = new ArrayList<>(scope.args());
        args.add(logicalTableName);
        try {
            return jdbcTemplate.queryForObject(
                    "SELECT * FROM DATA_MODEL_TABLE WHERE " + scope.sql() + " ORDER BY "
                            + "CASE ISOLATION_MODE "
                            + "WHEN 'PROJECT_ISOLATED' THEN 4 "
                            + "WHEN 'PROJECT_SHARED' THEN 3 "
                            + "WHEN 'TENANT_ISOLATED' THEN 2 "
                            + "WHEN 'TENANT_SHARED' THEN 1 "
                            + "ELSE 0 END DESC, UPDATED_AT DESC LIMIT 1",
                    (rs, rowNum) -> readTableInfo(rs),
                    args.toArray()
            );
        } catch (EmptyResultDataAccessException e) {
            return null;
        }
    }

