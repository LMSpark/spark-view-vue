    private Map<String, Object> toIntrospectionPayload(IntrospectedColumn column) {
        Map<String, Object> payload = new LinkedHashMap<>();
        payload.put("name", toLowerCamel(column.columnName()));
        payload.put("physicalColumnName", column.columnName());
        payload.put("type", dataTypeFromSqlType(column));
        payload.put("sqlType", sqlTypeFromIntrospection(column));
        payload.put("primaryKey", column.primaryKey());
        payload.put("autoIncrement", column.autoIncrement());
        payload.put("nullable", column.nullable());
        payload.put("ordinalPosition", column.ordinalPosition());
        payload.put("size", column.size());
        payload.put("scale", column.scale());
        payload.put("defaultValue", column.defaultValue());
        return payload;
    }

    private List<Map<String, Object>> readImportTables(Map<String, Object> body) {
        Object tablesValue = body == null ? null : body.get("tables");
        if (!(tablesValue instanceof List<?> rawList)) {
            throw new IllegalArgumentException("tables 必须是数组");
        }
        List<Map<String, Object>> tables = new ArrayList<>();
        for (Object item : rawList) {
            if (!(item instanceof Map<?, ?> rawMap)) {
                throw new IllegalArgumentException("tables 内每项必须是对象");
            }
            tables.add(toStringKeyMap(rawMap));
        }
        return tables;
    }

    private List<ColumnDraft> readColumnDrafts(Object value) {
        if (!(value instanceof List<?> rawList)) {
            throw new IllegalArgumentException("columns 必须是数组");
        }
        List<ColumnDraft> columns = new ArrayList<>();
        for (Object item : rawList) {
            if (!(item instanceof Map<?, ?> rawColumn)) {
                throw new IllegalArgumentException("columns 内每项必须是对象");
            }
            Map<String, Object> column = toStringKeyMap(rawColumn);
            String logicalName = readRequiredIdentifier(column.get("name"), "columns.name");
            String physicalName = readOptionalIdentifier(column.get("physicalColumnName"));
            if (physicalName == null) {
                physicalName = toUpperSnake(logicalName);
            }
            String dataType = stringOrDefault(column.get("type"), "string");
            Integer maxLength = readNullableInt(column.get("maxLength"));
            Integer precision = readNullableInt(column.get("numericPrecision"));
            Integer scale = readNullableInt(column.get("numericScale"));
            boolean primaryKey = readBoolean(column.get("primaryKey"), "id".equals(logicalName));
            boolean autoIncrement = readBoolean(column.get("autoIncrement"), primaryKey && isNumericDataType(dataType));
            boolean nullable = !primaryKey && !readBoolean(column.get("required"), false) && readBoolean(column.get("nullable"), true);
            String sqlType = stringOrDefault(column.get("sqlType"), dialect.sqlTypeFromDataType(dataType, maxLength, precision, scale));
            columns.add(new ColumnDraft(
                    logicalName,
                    physicalName,
                    dataType,
                    sqlType,
                    primaryKey,
                    autoIncrement,
                    nullable,
                    maxLength,
                    precision,
                    scale,
                    stringOrDefault(column.get("label"), humanizeLabel(logicalName))
            ));
        }
        return columns;
    }

    private List<ColumnDraft> ensurePrimaryKeyDraft(List<ColumnDraft> columns) {
        boolean hasPrimaryKey = columns.stream().anyMatch(ColumnDraft::primaryKey);
        if (hasPrimaryKey) return columns;
        List<ColumnDraft> result = new ArrayList<>();
        result.add(new ColumnDraft("id", "ID", "number", dialect.bigIntType(), true, true, false, null, null, null, "ID"));
        result.addAll(columns);
        return result;
    }

    private Map<String, ColumnInfo> byColumnName(Collection<ColumnInfo> columns) {
        Map<String, ColumnInfo> result = new LinkedHashMap<>();
        for (ColumnInfo column : columns) {
            result.put(column.columnName(), column);
        }
        return result;
    }

    private static boolean hasColumn(IntrospectedTable table, String columnName) {
        return table.columns().stream().anyMatch(column -> column.columnName().equalsIgnoreCase(columnName));
    }

    private static String readRequiredIdentifier(Object value, String fieldName) {
        if (!(value instanceof String text) || text.isBlank()) {
            throw new IllegalArgumentException(fieldName + " 不能为空");
        }
        String trimmed = text.trim();
        assertIdentifier(trimmed, fieldName);
        return trimmed;
    }

    private static String readOptionalIdentifier(Object value) {
        if (value == null) return null;
        if (!(value instanceof String text) || text.isBlank()) return null;
        String trimmed = text.trim();
        assertIdentifier(trimmed, "identifier");
        return trimmed;
    }

    private static String stringOrDefault(Object value, String defaultValue) {
        if (value == null) return defaultValue;
        String text = String.valueOf(value).trim();
        return text.isEmpty() ? defaultValue : text;
    }

    private static boolean readBoolean(Object value, boolean defaultValue) {
        if (value == null) return defaultValue;
        if (value instanceof Boolean bool) return bool;
        if (value instanceof String text) return Boolean.parseBoolean(text);
        return defaultValue;
    }

    private static Integer readNullableInt(Object value) {
        if (value == null) return null;
        if (value instanceof Number number) return number.intValue();
        if (value instanceof String text && !text.isBlank()) return Integer.parseInt(text.trim());
        return null;
    }

    private static Long readNullableLong(Object value) {
        if (value == null) return null;
        if (value instanceof Number number) return number.longValue();
        if (value instanceof String text && !text.isBlank()) return Long.parseLong(text.trim());
        return null;
    }

