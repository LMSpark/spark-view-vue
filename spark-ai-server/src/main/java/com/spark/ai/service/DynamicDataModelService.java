    private boolean isMySql() {
        try (Connection connection = dataSource.getConnection()) {
            String product = connection.getMetaData().getDatabaseProductName();
            return product != null && product.toLowerCase(Locale.ROOT).contains("mysql");
        } catch (Exception ignored) {
            return false;
        }
    }

    public List<Map<String, Object>> listTables(String tenantId, String projectId) {
        guardProject(tenantId, projectId);
        return jdbcTemplate.query("""
            SELECT * FROM DATA_MODEL_TABLE
            WHERE TENANT_ID = ? AND PROJECT_ID = ?
            ORDER BY LOGICAL_TABLE_NAME
            """, (rs, rowNum) -> toTableSummary(readTableInfo(rs)), tenantId, projectId);
    }

    public Map<String, Object> getTablePayload(String tenantId, String projectId, String logicalTableName) {
        guardProject(tenantId, projectId);
        TableDefinition definition = requireDefinition(tenantId, projectId, logicalTableName);
        return toFullTablePayload(definition);
    }

    @Transactional
    public Map<String, Object> createTable(String tenantId, String projectId, Map<String, Object> body) {
        guardProject(tenantId, projectId);
        String logicalName = readRequiredIdentifier(body.get("tableName"), "tableName");
        if (findTable(tenantId, projectId, logicalName) != null) {
            throw new ResponseStatusException(HttpStatus.CONFLICT, "逻辑表已存在: " + logicalName);
        }

        List<ColumnDraft> columns = readColumnDrafts(body.get("columns"));
        columns = ensurePrimaryKeyDraft(columns);
        String physicalName = readOptionalIdentifier(body.get("physicalTableName"));
        if (physicalName == null) {
            physicalName = generatePhysicalTableName(tenantId, projectId, logicalName);
        }
        assertIdentifier(physicalName, "physicalTableName");

        createPhysicalTable(physicalName, columns);
        return persistImportedOrCreatedTable(
                tenantId,
                projectId,
                logicalName,
                physicalName,
                ORIGIN_DYNAMIC_CREATED,
                body,
                scanPhysicalTable(physicalName),
                readViews(body.get("views"))
        );
    }

    @Transactional
    public Map<String, Object> updateTable(String tenantId, String projectId, String logicalTableName, Map<String, Object> body) {
        guardProject(tenantId, projectId);
        TableDefinition current = requireDefinition(tenantId, projectId, logicalTableName);
        boolean force = readBoolean(body.get("force"), false);
        List<Map<String, Object>> dangerous = new ArrayList<>();
        List<ColumnDraft> desired = body.containsKey("columns")
                ? ensurePrimaryKeyDraft(readColumnDrafts(body.get("columns")))
                : current.columns().stream().map(ColumnDraft::fromColumnInfo).toList();

        Map<String, ColumnInfo> existingByName = byColumnName(current.columns());
        Set<String> desiredNames = new LinkedHashSet<>();
        for (ColumnDraft draft : desired) {
            desiredNames.add(draft.columnName());
            ColumnInfo existing = existingByName.get(draft.columnName());
            if (existing == null) {
                jdbcTemplate.execute("ALTER TABLE " + q(current.table().physicalTableName())
                        + " ADD COLUMN " + q(draft.physicalColumnName()) + " " + draft.sqlType());
                continue;
            }
            if (!normalizeSqlType(existing.sqlType()).equals(normalizeSqlType(draft.sqlType()))) {
                dangerous.add(Map.of(
                        "kind", "type-change",
                        "column", draft.columnName(),
                        "from", existing.sqlType(),
                        "to", draft.sqlType()
                ));
            }
            if (existing.nullable() && !draft.nullable()) {
                dangerous.add(Map.of("kind", "nullable-tighten", "column", draft.columnName()));
            }
        }

        for (ColumnInfo existing : current.columns()) {
            if (!desiredNames.contains(existing.columnName())) {
                dangerous.add(Map.of("kind", "drop-column", "column", existing.columnName()));
            }
        }

        if (!dangerous.isEmpty() && !force) {
            throw new PreflightRequiredException(Map.of(
                    "message", "结构变更包含危险操作，需要 force=true",
                    "changes", dangerous
            ));
        }

        if (force) {
            for (ColumnDraft draft : desired) {
                ColumnInfo existing = existingByName.get(draft.columnName());
                if (existing == null) continue;
                if (!normalizeSqlType(existing.sqlType()).equals(normalizeSqlType(draft.sqlType()))) {
                    jdbcTemplate.execute("ALTER TABLE " + q(current.table().physicalTableName())
                            + " ALTER COLUMN " + q(existing.physicalColumnName()) + " " + draft.sqlType());
                }
                if (existing.nullable() && !draft.nullable()) {
                    jdbcTemplate.execute("ALTER TABLE " + q(current.table().physicalTableName())
                            + " ALTER COLUMN " + q(existing.physicalColumnName()) + " SET NOT NULL");
                }
            }
            for (ColumnInfo existing : current.columns()) {
                if (!desiredNames.contains(existing.columnName())) {
                    jdbcTemplate.execute("ALTER TABLE " + q(current.table().physicalTableName())
                            + " DROP COLUMN " + q(existing.physicalColumnName()));
                }
            }
        }

        IntrospectedTable introspected = scanPhysicalTable(current.table().physicalTableName());
        replaceColumnsFromIntrospection(current.table().id(), introspected);
        if (body.containsKey("views")) {
            replaceViews(current.table().id(), readViews(body.get("views")));
        }
        updateTableHashAndVersion(current.table().id(), hashTable(introspected), current.table().schemaVersion() + 1);
        return getTablePayload(tenantId, projectId, logicalTableName);
    }

    @Transactional
    public void deleteTable(String tenantId, String projectId, String logicalTableName, boolean forceDropPhysical) {
        guardProject(tenantId, projectId);
        TableDefinition definition = requireDefinition(tenantId, projectId, logicalTableName);
        jdbcTemplate.update("DELETE FROM DATA_MODEL_VIEW WHERE TABLE_ID = ?", definition.table().id());
        jdbcTemplate.update("DELETE FROM DATA_MODEL_COLUMN WHERE TABLE_ID = ?", definition.table().id());
        jdbcTemplate.update("DELETE FROM DATA_MODEL_TABLE WHERE ID = ?", definition.table().id());
        if (forceDropPhysical) {
            jdbcTemplate.execute("DROP TABLE IF EXISTS " + q(definition.table().physicalTableName()));
        }
    }

    public Map<String, Object> consistency(String tenantId, String projectId, String logicalTableName) {
        guardProject(tenantId, projectId);
        TableDefinition definition = requireDefinition(tenantId, projectId, logicalTableName);
        IntrospectedTable physical = scanPhysicalTable(definition.table().physicalTableName());
        List<Map<String, Object>> differences = diff(definition, physical);
        return Map.of(
                "consistent", differences.isEmpty(),
                "logicalTableName", definition.table().logicalTableName(),
                "physicalTableName", definition.table().physicalTableName(),
                "differences", differences,
                "ddlHash", hashTable(physical)
        );
    }

    @Transactional
    public Map<String, Object> reconcile(String tenantId, String projectId, String logicalTableName) {
        guardProject(tenantId, projectId);
        TableDefinition definition = requireDefinition(tenantId, projectId, logicalTableName);
        IntrospectedTable physical = scanPhysicalTable(definition.table().physicalTableName());
        replaceColumnsFromIntrospection(definition.table().id(), physical);
        updateTableHashAndVersion(definition.table().id(), hashTable(physical), definition.table().schemaVersion() + 1);
        return getTablePayload(tenantId, projectId, logicalTableName);
    }

    public List<Map<String, Object>> listPhysicalTables() {
        return listPhysicalTableNames().stream()
                .map(name -> describePhysicalTable(name, false))
                .toList();
    }

    public Map<String, Object> describePhysicalTable(String physicalTableName) {
        return describePhysicalTable(physicalTableName, true);
    }

    @Transactional
    public List<Map<String, Object>> importExistingTables(String tenantId, String projectId, Map<String, Object> body) {
        guardProject(tenantId, projectId);
        List<Map<String, Object>> tables = readImportTables(body);
        List<Map<String, Object>> imported = new ArrayList<>();
        for (Map<String, Object> tableRequest : tables) {
            String physicalName = readRequiredIdentifier(tableRequest.get("physicalTableName"), "physicalTableName");
            String logicalName = readOptionalIdentifier(tableRequest.get("logicalTableName"));
            if (logicalName == null) {
                logicalName = toLowerCamel(physicalName);
            }
            if (findTable(tenantId, projectId, logicalName) != null) {
                throw new ResponseStatusException(HttpStatus.CONFLICT, "逻辑表已存在: " + logicalName);
            }

            IntrospectedTable before = scanPhysicalTable(physicalName);
            ensureManagedPhysicalShape(tenantId, projectId, before);
            IntrospectedTable after = scanPhysicalTable(physicalName);
            Map<String, Object> requestBody = new LinkedHashMap<>(tableRequest);
            requestBody.put("resourceType", "database-table");
            requestBody.put("resourceId", logicalName);
            imported.add(persistImportedOrCreatedTable(
                    tenantId,
                    projectId,
                    logicalName,
                    physicalName,
                    ORIGIN_EXISTING_IMPORTED,
                    requestBody,
                    after,
                    readViews(tableRequest.get("views"))
            ));
        }
        return imported;
    }

    public TableDefinition requireDefinition(String tenantId, String projectId, String logicalTableName) {
        guardProject(tenantId, projectId);
        TableInfo table = findTable(tenantId, projectId, logicalTableName);
        if (table == null) {
            throw new NoSuchElementException("数据表元数据不存在: " + logicalTableName);
        }
        List<ColumnInfo> columns = listColumns(table.id());
        Map<String, Map<String, Object>> views = listViews(table.id());
        return new TableDefinition(table, columns, views);
    }

    private void guardProject(String tenantId, String projectId) {
        if (accessGuardService != null) {
            accessGuardService.requireProjectAccess(tenantId, projectId);
        }
    }

    public static String q(String identifier) {
        assertIdentifier(identifier, "identifier");
        return "\"" + identifier + "\"";
    }

    public static void assertIdentifier(String identifier, String fieldName) {
        if (identifier == null || !IDENTIFIER.matcher(identifier).matches()) {
            throw new IllegalArgumentException(fieldName + " 不是合法 SQL 标识符: " + identifier);
        }
    }

    private Map<String, Object> persistImportedOrCreatedTable(
            String tenantId,
            String projectId,
            String logicalName,
            String physicalName,
            String origin,
            Map<String, Object> requestBody,
            IntrospectedTable introspected,
            Map<String, Map<String, Object>> views
    ) {
        String primaryKey = introspected.primaryKeyColumns().stream()
                .findFirst()
                .map(DynamicDataModelService::toLowerCamel)
                .orElse("id");
        Timestamp now = Timestamp.from(Instant.now());
        String ddlHash = hashTable(introspected);
        jdbcTemplate.update("""
            INSERT INTO DATA_MODEL_TABLE (
                TENANT_ID, PROJECT_ID, LOGICAL_TABLE_NAME, ORIGIN, MANAGED_MODE,
                PHYSICAL_TABLE_NAME, PRIMARY_KEY_FIELD, RESOURCE_TYPE, RESOURCE_ID,
                BUSINESS_CATEGORY, SCHEMA_VERSION, DDL_HASH, STATUS,
                LAST_INTROSPECTED_AT, CREATED_AT, UPDATED_AT
            ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, 'active', ?, ?, ?)
            """,
                tenantId,
                projectId,
                logicalName,
                origin,
                MANAGED_MODE_STRICT,
                introspected.tableName(),
                primaryKey,
                stringOrDefault(requestBody.get("resourceType"), "database-table"),
                stringOrDefault(requestBody.get("resourceId"), logicalName),
                stringOrDefault(requestBody.get("businessCategory"), null),
                1,
                ddlHash,
                now,
                now,
                now
        );
        TableInfo table = Objects.requireNonNull(findTable(tenantId, projectId, logicalName));
        replaceColumnsFromIntrospection(table.id(), introspected);
        if (views.isEmpty()) {
            Map<String, Object> defaultView = new LinkedHashMap<>();
            defaultView.put("viewId", "default");
            defaultView.put("page", 1);
            defaultView.put("pageSize", 20);
            views = Map.of("default", defaultView);
        }
        replaceViews(table.id(), views);
        return getTablePayload(tenantId, projectId, logicalName);
    }

    private void createPhysicalTable(String physicalName, List<ColumnDraft> columns) {
        List<String> definitions = new ArrayList<>();
        definitions.add(q("TENANT_ID") + " VARCHAR(255) NOT NULL");
        definitions.add(q("PROJECT_ID") + " VARCHAR(255) NOT NULL");
        for (ColumnDraft column : columns) {
            String definition = q(column.physicalColumnName()) + " " + column.sqlType();
            if (column.autoIncrement()) {
                definition += " GENERATED BY DEFAULT AS IDENTITY";
            }
            if (!column.nullable() && !column.autoIncrement()) {
                definition += " NOT NULL";
            }
            if (column.primaryKey()) {
                definition += " PRIMARY KEY";
            }
            definitions.add(definition);
        }
        jdbcTemplate.execute("CREATE TABLE " + q(physicalName) + " (" + String.join(", ", definitions) + ")");
        jdbcTemplate.execute("CREATE INDEX IF NOT EXISTS " + q("IDX_" + physicalName + "_SCOPE")
                + " ON " + q(physicalName) + " (" + q("TENANT_ID") + ", " + q("PROJECT_ID") + ")");
    }

    private void ensureManagedPhysicalShape(String tenantId, String projectId, IntrospectedTable table) {
        boolean hasPrimaryKey = !table.primaryKeyColumns().isEmpty();
        if (!hasColumn(table, "TENANT_ID")) {
            jdbcTemplate.execute("ALTER TABLE " + q(table.tableName()) + " ADD COLUMN " + q("TENANT_ID") + " VARCHAR(255)");
            jdbcTemplate.update("UPDATE " + q(table.tableName()) + " SET " + q("TENANT_ID") + " = ? WHERE " + q("TENANT_ID") + " IS NULL", tenantId);
            tryAlter("ALTER TABLE " + q(table.tableName()) + " ALTER COLUMN " + q("TENANT_ID") + " SET NOT NULL");
        }
        if (!hasColumn(table, "PROJECT_ID")) {
            jdbcTemplate.execute("ALTER TABLE " + q(table.tableName()) + " ADD COLUMN " + q("PROJECT_ID") + " VARCHAR(255)");
            jdbcTemplate.update("UPDATE " + q(table.tableName()) + " SET " + q("PROJECT_ID") + " = ? WHERE " + q("PROJECT_ID") + " IS NULL", projectId);
            tryAlter("ALTER TABLE " + q(table.tableName()) + " ALTER COLUMN " + q("PROJECT_ID") + " SET NOT NULL");
        }
        if (!hasPrimaryKey) {
            jdbcTemplate.execute("ALTER TABLE " + q(table.tableName()) + " ADD COLUMN " + q("ID") + " BIGINT GENERATED BY DEFAULT AS IDENTITY");
            tryAlter("ALTER TABLE " + q(table.tableName()) + " ADD PRIMARY KEY (" + q("ID") + ")");
        }
        jdbcTemplate.execute("CREATE INDEX IF NOT EXISTS " + q("IDX_" + table.tableName() + "_SCOPE")
                + " ON " + q(table.tableName()) + " (" + q("TENANT_ID") + ", " + q("PROJECT_ID") + ")");
    }

    private void tryAlter(String sql) {
        try {
            jdbcTemplate.execute(sql);
        } catch (Exception ignored) {
            // H2 对部分历史表约束变更会拒绝；接管流程随后用 consistency 暴露差异。
        }
    }

    private IntrospectedTable scanPhysicalTable(String physicalTableName) {
        assertIdentifier(physicalTableName, "physicalTableName");
        try (Connection connection = dataSource.getConnection()) {
            DatabaseMetaData metaData = connection.getMetaData();
            String tableName = resolveActualTableName(metaData, physicalTableName);
            if (tableName == null) {
                throw new NoSuchElementException("物理表不存在: " + physicalTableName);
            }

            Set<String> primaryKeys = new LinkedHashSet<>();
            try (ResultSet pk = metaData.getPrimaryKeys(null, null, tableName)) {
                while (pk.next()) {
                    primaryKeys.add(pk.getString("COLUMN_NAME"));
                }
            }

            List<IntrospectedColumn> columns = new ArrayList<>();
            try (ResultSet rs = metaData.getColumns(null, null, tableName, null)) {
                while (rs.next()) {
                    String columnName = rs.getString("COLUMN_NAME");
                    int sqlTypeCode = rs.getInt("DATA_TYPE");
                    String typeName = rs.getString("TYPE_NAME");
                    int size = rs.getInt("COLUMN_SIZE");
                    int scale = rs.getInt("DECIMAL_DIGITS");
                    boolean nullable = rs.getInt("NULLABLE") != DatabaseMetaData.columnNoNulls;
                    String defaultValue = rs.getString("COLUMN_DEF");
                    int ordinalPosition = rs.getInt("ORDINAL_POSITION");
                    String autoIncrement = "";
                    try {
                        autoIncrement = rs.getString("IS_AUTOINCREMENT");
                    } catch (Exception ignored) {
                        // Driver optional column.
                    }
                    columns.add(new IntrospectedColumn(
                            columnName,
                            sqlTypeCode,
                            typeName,
                            size > 0 ? size : null,
                            scale >= 0 ? scale : null,
                            nullable,
                            defaultValue,
                            primaryKeys.contains(columnName),
                            "YES".equalsIgnoreCase(autoIncrement),
                            ordinalPosition
                    ));
                }
            }
            columns.sort(Comparator.comparingInt(IntrospectedColumn::ordinalPosition));
            return new IntrospectedTable(tableName, columns, primaryKeys);
        } catch (SQLException e) {
            throw new IllegalStateException("扫描数据库表失败: " + physicalTableName, e);
        }
    }

    private String resolveActualTableName(DatabaseMetaData metaData, String requestedName) throws SQLException {
        try (ResultSet rs = metaData.getTables(null, null, requestedName, new String[]{"TABLE"})) {
            if (rs.next()) return rs.getString("TABLE_NAME");
        }
        try (ResultSet rs = metaData.getTables(null, null, requestedName.toUpperCase(Locale.ROOT), new String[]{"TABLE"})) {
            if (rs.next()) return rs.getString("TABLE_NAME");
        }
        return null;
    }

    private List<String> listPhysicalTableNames() {
        try (Connection connection = dataSource.getConnection()) {
            DatabaseMetaData metaData = connection.getMetaData();
            List<String> names = new ArrayList<>();
            try (ResultSet rs = metaData.getTables(null, null, null, new String[]{"TABLE"})) {
                while (rs.next()) {
                    String schema = rs.getString("TABLE_SCHEM");
                    String name = rs.getString("TABLE_NAME");
                    if (isImportableTable(schema, name)) {
                        names.add(name);
                    }
                }
            }
            names.sort(String::compareToIgnoreCase);
            return names;
        } catch (SQLException e) {
            throw new IllegalStateException("扫描数据库表失败", e);
        }
    }

    private boolean isImportableTable(String schema, String tableName) {
        if (tableName == null) return false;
        String upperSchema = schema == null ? "" : schema.toUpperCase(Locale.ROOT);
        String upper = tableName.toUpperCase(Locale.ROOT);
        if (upperSchema.contains("INFORMATION_SCHEMA")) return false;
        if (upper.startsWith("SYS")) return false;
        return !RESERVED_TABLES.contains(upper);
    }

