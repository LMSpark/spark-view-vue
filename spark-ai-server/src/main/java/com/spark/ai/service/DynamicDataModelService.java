    private static boolean hasColumn(IntrospectedTable table, String columnName) {
        return table.columns().stream().anyMatch(column -> column.columnName().equalsIgnoreCase(columnName));
    }

    private static String readRequiredIdentifier(Object value, String fieldName) {
        if (!(value instanceof String text) || text.isBlank()) {
            throw new IllegalArgumentException(fieldName + " 不能为空");
        }
        String trimmed = text.trim();
        assertIdentifier(trimmed, fieldName);
        return trimmed;
    }

    private static String readOptionalIdentifier(Object value) {
        if (value == null) return null;
        if (!(value instanceof String text) || text.isBlank()) return null;
        String trimmed = text.trim();
        assertIdentifier(trimmed, "identifier");
        return trimmed;
    }

    private static String stringOrDefault(Object value, String defaultValue) {
        if (value == null) return defaultValue;
        String text = String.valueOf(value).trim();
        return text.isEmpty() ? defaultValue : text;
    }

    private static boolean readBoolean(Object value, boolean defaultValue) {
        if (value == null) return defaultValue;
        if (value instanceof Boolean bool) return bool;
        if (value instanceof String text) return Boolean.parseBoolean(text);
        return defaultValue;
    }

    private static Integer readNullableInt(Object value) {
        if (value == null) return null;
        if (value instanceof Number number) return number.intValue();
        if (value instanceof String text && !text.isBlank()) return Integer.parseInt(text.trim());
        return null;
    }

    private static Map<String, Object> toStringKeyMap(Map<?, ?> raw) {
        Map<String, Object> result = new LinkedHashMap<>();
        raw.forEach((key, value) -> result.put(String.valueOf(key), value));
        return result;
    }

    private String writeJson(Object value) {
        try {
            return objectMapper.writeValueAsString(value);
        } catch (Exception e) {
            throw new IllegalArgumentException("JSON 序列化失败", e);
        }
    }

    private Map<String, Object> readJsonMap(String json) {
        if (json == null || json.isBlank()) return new LinkedHashMap<>();
        try {
            @SuppressWarnings("unchecked")
            Map<String, Object> result = objectMapper.readValue(json, LinkedHashMap.class);
            return result;
        } catch (Exception e) {
            throw new IllegalStateException("读取元数据 JSON 失败", e);
        }
    }

    private static String generatePhysicalTableName(String tenantId, String projectId, String logicalName) {
        String seed = tenantId + ":" + projectId + ":" + logicalName;
        return "APP_DATA_" + shortHash(seed).toUpperCase(Locale.ROOT);
    }

    private static String hashTable(IntrospectedTable table) {
        StringBuilder builder = new StringBuilder(table.tableName()).append('|');
        for (IntrospectedColumn column : table.columns()) {
            builder.append(column.columnName()).append(':')
                    .append(column.typeName()).append(':')
                    .append(column.size()).append(':')
                    .append(column.scale()).append(':')
                    .append(column.nullable()).append(':')
                    .append(column.primaryKey()).append(';');
        }
        return sha256(builder.toString());
    }

    private static String shortHash(String text) {
        return sha256(text).substring(0, 16);
    }

    private static String sha256(String text) {
        try {
            MessageDigest digest = MessageDigest.getInstance("SHA-256");
            byte[] bytes = digest.digest(text.getBytes(StandardCharsets.UTF_8));
            StringBuilder builder = new StringBuilder();
            for (byte b : bytes) {
                builder.append(String.format("%02x", b));
            }
            return builder.toString();
        } catch (Exception e) {
            throw new IllegalStateException("SHA-256 不可用", e);
        }
    }

    private static String toUpperSnake(String logicalName) {
        StringBuilder builder = new StringBuilder();
        for (int i = 0; i < logicalName.length(); i++) {
            char c = logicalName.charAt(i);
            if (Character.isUpperCase(c) && i > 0) {
                builder.append('_');
            }
            builder.append(Character.toUpperCase(c));
        }
        return builder.toString().replaceAll("[^A-Z0-9_]", "_");
    }

    public static String toLowerCamel(String physicalName) {
        String[] parts = physicalName.toLowerCase(Locale.ROOT).split("_+");
        if (parts.length == 0) return physicalName.toLowerCase(Locale.ROOT);
        StringBuilder builder = new StringBuilder(parts[0]);
        for (int i = 1; i < parts.length; i++) {
            if (parts[i].isEmpty()) continue;
            builder.append(Character.toUpperCase(parts[i].charAt(0))).append(parts[i].substring(1));
        }
        return builder.toString();
    }

    private static String humanizeLabel(String logicalName) {
        if ("id".equals(logicalName)) return "ID";
        String withSpaces = logicalName.replaceAll("([a-z])([A-Z])", "$1 $2");
        return Character.toUpperCase(withSpaces.charAt(0)) + withSpaces.substring(1);
    }

    private static String sqlTypeFromDataType(String dataType, Integer maxLength, Integer precision, Integer scale) {
        return switch (dataType.toLowerCase(Locale.ROOT)) {
            case "int", "integer" -> "INT";
            case "number", "long", "bigint" -> "BIGINT";
            case "decimal" -> "DECIMAL(" + (precision != null ? precision : 18) + "," + (scale != null ? scale : 2) + ")";
            case "float", "double" -> "DOUBLE";
            case "boolean", "bool" -> "BOOLEAN";
            case "date" -> "DATE";
            case "datetime", "timestamp" -> "TIMESTAMP";
            case "time" -> "TIME";
            case "text", "object", "array" -> "CLOB";
            default -> "VARCHAR(" + (maxLength != null ? maxLength : 255) + ")";
        };
    }

    private static boolean isNumericDataType(String dataType) {
        String normalized = dataType.toLowerCase(Locale.ROOT);
        return Set.of("int", "integer", "number", "long", "bigint").contains(normalized);
    }

    private static String dataTypeFromSqlType(IntrospectedColumn column) {
        return switch (column.sqlTypeCode()) {
            case Types.INTEGER, Types.SMALLINT, Types.TINYINT -> "integer";
            case Types.BIGINT, Types.NUMERIC, Types.DECIMAL, Types.DOUBLE, Types.FLOAT, Types.REAL -> "number";
            case Types.BOOLEAN, Types.BIT -> "boolean";
            case Types.DATE -> "date";
            case Types.TIMESTAMP, Types.TIMESTAMP_WITH_TIMEZONE -> "datetime";
            case Types.TIME, Types.TIME_WITH_TIMEZONE -> "time";
            case Types.CLOB, Types.LONGVARCHAR, Types.LONGNVARCHAR -> "text";
            default -> "string";
        };
    }

    private static String sqlTypeFromIntrospection(IntrospectedColumn column) {
        String type = column.typeName() == null ? "VARCHAR" : column.typeName().toUpperCase(Locale.ROOT);
        if ((type.contains("CHAR") || type.contains("VARCHAR")) && column.size() != null && column.size() > 0) {
            return "VARCHAR(" + column.size() + ")";
        }
        if ((type.contains("DECIMAL") || type.contains("NUMERIC")) && column.size() != null && column.scale() != null) {
            return "DECIMAL(" + column.size() + "," + column.scale() + ")";
        }
        if (type.contains("IDENTITY")) return "BIGINT";
        return type.replace(" CHARACTER VARYING", "VARCHAR");
    }

    private static String normalizeSqlType(String sqlType) {
        return sqlType == null ? "" : sqlType.toUpperCase(Locale.ROOT).replaceAll("\\s+", " ").trim();
    }

